  function ss() {
    try { return (typeof self !== 'undefined' ? self : this).sessionStorage || null; } catch (e) { return null; }
  }

  function lang() {
    try {
      var s = ss();
      var v = s ? s.getItem(LANG_KEY) : null;
      return (v === 'en' || v === 'ms') ? v : DEFAULT_LANG;
    } catch (e) { return DEFAULT_LANG; }
  }

  function setLang(code) {
    var next = (code === 'ms') ? 'ms' : 'en';
    try { var s = ss(); if (s) s.setItem(LANG_KEY, next); } catch (e) { /* ignore */ }
    return next;
  }

  function resolve(obj, parts) {
    var cur = obj;
    for (var i = 0; i < parts.length; i++) {
      if (!cur || typeof cur !== 'object') return undefined;
      cur = cur[parts[i]];
    }
    return typeof cur === 'string' ? cur : undefined;
  }

